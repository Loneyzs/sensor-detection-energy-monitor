#!/usr/bin/env python3
"""Generate a small DejaVu ASCII / Noto Sans CJK SC bitmap subset for the OLED (Pillow required)."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
root = Path(__file__).resolve().parent.parent
font_path = '/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc'
chinese = sorted(set('已断电按键恢复供启动宽限状态中待机计时异常解除传感器输出关闭阈值等待即将秒取消功率超'))
rows = ['/* Generated by tools/generate_font.py. CJK: Noto (SIL OFL 1.1); ASCII: DejaVu (Bitstream Vera license). */',
        '#ifndef ENERGY_FONT_H', '#define ENERGY_FONT_H',
        '#include <stdint.h>',
        'struct font_glyph { uint32_t codepoint; uint8_t width, height; uint16_t rows[12]; };',
        'static const struct font_glyph font_glyphs[] = {']
for char in [chr(n) for n in range(32, 127)] + chinese:
    ascii_char = ord(char) < 128
    width, height = (6, 8) if ascii_char else (12, 12)
    # Noto Mono at 8px gives readable, fixed 5px glyph bodies plus spacing.
    path = '/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf' if ascii_char else font_path
    font = ImageFont.truetype(path, 8 if ascii_char else 12, index=0 if ascii_char else 2)
    im = Image.new('L', (width, height))
    draw = ImageDraw.Draw(im)
    box = draw.textbbox((0, 0), char, font=font)
    # Align ASCII to one baseline, including descenders; fit CJK to its cell.
    y = -2 if ascii_char else -box[1]
    draw.text((0, y), char, fill=255, font=font)
    values = [sum((1 << x) for x in range(width) if im.getpixel((x, y)) >= 96)
              for y in range(height)]
    values += [0] * (12 - height)
    rows.append('    {0x%04x, %d, %d, {%s}}, /* %s */' %
                (ord(char), width, height, ','.join('0x%03x' % n for n in values), char))
rows += ['};', '#endif', '']
(root / 'src/font.h').write_text('\n'.join(rows))
